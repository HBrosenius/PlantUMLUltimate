#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md (repository root) and apps/web/public/third-party-notices.txt (served by the app
// and linked from Help) from apps/web/src/third-party-credits.json, the bundled theme headers and the licence files
// the credits point at. Run `node scripts/third-party-notices.mjs` after bundling new third-party content;
// `--check` exits 1 when the files are out of date. A unit test runs the same check.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const NOTICES_PATH = "THIRD_PARTY_NOTICES.md";
export const PUBLIC_NOTICES_PATH = "apps/web/public/third-party-notices.txt";

/** The `key: value` lines of a theme's `---` header. */
function themeHeader(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  const fields = {};
  for (const line of (match?.[1] ?? "").split(/\r?\n/)) {
    const field = /^([a-z_]+):\s*(.*)$/.exec(line);
    if (field) fields[field[1]] = field[2].trim();
  }
  return fields;
}

function themesTable(root, folder) {
  const rows = readdirSync(join(root, folder))
    .filter((file) => /^puml-theme-.*\.puml$/.test(file))
    .sort()
    .map((file) => {
      const header = themeHeader(readFileSync(join(root, folder, file), "utf8"));
      const name = header.name || file.replace(/^puml-theme-|\.puml$/g, "");
      const author = header.author || "Not stated";
      const licence = header.license || "Not stated (part of the PlantUML project)";
      return `| ${name} | ${author} | ${licence} |`;
    });
  return ["| Theme | Author | Licence |", "| --- | --- | --- |", ...rows].join("\n");
}

/** The full notices text. `root` is the repository root. */
export function buildNotices(root = repositoryRoot) {
  const { credits } = JSON.parse(readFileSync(join(root, "apps/web/src/third-party-credits.json"), "utf8"));
  const sections = credits.map((credit) => {
    const lines = [
      `## ${credit.name}`,
      "",
      credit.use,
      "",
      `- Copyright: ${credit.copyright}`,
      `- Licence: ${credit.licence}`,
      `- Source: ${credit.url}`,
    ];
    if (credit.themes) lines.push("", themesTable(root, credit.themes));
    if (credit.licenceFile) {
      const text = readFileSync(join(root, credit.licenceFile), "utf8").replace(/\r\n?/g, "\n").trimEnd();
      lines.push("", "```text", text, "```");
    }
    return lines.join("\n");
  });
  return [
    "# Third-party notices",
    "",
    "PlantUML Ultimate bundles the third-party content below and runs it on your device; nothing listed here is",
    "fetched at runtime. npm packages used to build the app carry their own licence files in their packages.",
    "",
    "Generated by `node scripts/third-party-notices.mjs` from `apps/web/src/third-party-credits.json`. Do not edit by hand.",
    "",
    ...sections.flatMap((section) => [section, ""]),
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const text = buildNotices();
  const targets = [NOTICES_PATH, PUBLIC_NOTICES_PATH];
  const stale = targets.filter((path) => {
    try {
      return readFileSync(join(repositoryRoot, path), "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (check) {
    if (stale.length) {
      console.error(`Out of date: ${stale.join(", ")}. Run node scripts/third-party-notices.mjs`);
      process.exit(1);
    }
    return;
  }
  for (const path of targets) writeFileSync(join(repositoryRoot, path), text);
  console.log(`Wrote ${targets.join(" and ")}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
