import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const directory = dirname(fileURLToPath(import.meta.url));
const voice = readFileSync(join(directory, "narration-edited.wav"));
const encoded = voice.toString("base64");
writeFileSync(
  join(directory, "voice-data.js"),
  `// Generated by build-voice-data.mjs so the film works from file:// in Chrome.\nwindow.FILM_VOICE_BASE64 = "${encoded}";\n`,
);
